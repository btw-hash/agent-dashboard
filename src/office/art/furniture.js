import { spr, inked, slab, tone, SHOE, INK } from '../engine/pixel.js';

const cache = new Map();
function chairBack(c) {
  const k = 'cb' + c;
  let v = cache.get(k);
  if (v) return v;
  v = inked(
    spr(14, 15, (R) => {
      slab(R, 1, 0, 12, 9, c);
      R(3, 2, 8, 1, tone(c, 0.2));
      R(0, 6, 2, 4, tone(c, -0.3));
      R(12, 6, 2, 4, tone(c, -0.3));
      R(6, 9, 2, 3, '#2a2e44');
      R(2, 12, 10, 1, '#2a2e44');
      R(1, 13, 2, 2, SHOE);
      R(6, 13, 2, 2, SHOE);
      R(11, 13, 2, 2, SHOE);
    })
  );
  cache.set(k, v);
  return v;
}
function chairTop(c) {
  const k = 'ct' + c;
  let v = cache.get(k);
  if (v) return v;
  v = inked(
    spr(14, 9, (R) => {
      slab(R, 0, 0, 14, 9, tone(c, -0.12));
      R(2, 2, 10, 1, tone(c, 0.15));
    })
  );
  cache.set(k, v);
  return v;
}
